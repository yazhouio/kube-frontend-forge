use std::{
    env,
    path::{Path, PathBuf},
};

#[derive(Clone, Copy)]
pub enum NodeModulesProfile {
    Job,
    Server,
}

impl NodeModulesProfile {
    fn required_packages(self) -> &'static [&'static str] {
        match self {
            Self::Job => &["esbuild", "@swc/core", "@frontend-forge/forge-components"],
            Self::Server => &["@frontend-forge/forge-components"],
        }
    }
}

pub fn resolve_build_node_modules_dir(profile: NodeModulesProfile) -> Option<PathBuf> {
    if let Some(explicit) = env::var("FORGE_NODE_MODULES_DIR")
        .ok()
        .filter(|value| !value.trim().is_empty())
    {
        return Some(PathBuf::from(explicit));
    }

    let mut roots = Vec::new();
    if let Ok(current_dir) = env::current_dir() {
        roots.push(current_dir);
    }
    if let Ok(current_exe) = env::current_exe()
        && let Some(parent) = current_exe.parent()
    {
        roots.push(parent.to_path_buf());
    }

    find_local_node_modules_dir(roots, profile)
}

fn find_local_node_modules_dir<I>(roots: I, profile: NodeModulesProfile) -> Option<PathBuf>
where
    I: IntoIterator<Item = PathBuf>,
{
    let mut candidates = Vec::new();
    for root in roots {
        for ancestor in root.ancestors() {
            push_unique(&mut candidates, ancestor.join("node_modules"));
            push_unique(
                &mut candidates,
                ancestor.join("crates/forge-job/node_modules"),
            );
            push_unique(
                &mut candidates,
                ancestor.join("crates/forge-server/node_modules"),
            );
        }
    }

    candidates
        .into_iter()
        .find(|path| is_local_build_node_modules(path, profile))
}

fn push_unique(paths: &mut Vec<PathBuf>, path: PathBuf) {
    if !paths.iter().any(|existing| existing == &path) {
        paths.push(path);
    }
}

fn is_local_build_node_modules(path: &Path, profile: NodeModulesProfile) -> bool {
    path.is_dir()
        && profile
            .required_packages()
            .iter()
            .all(|package| node_module_exists(path, package))
}

fn node_module_exists(node_modules_dir: &Path, package: &str) -> bool {
    package
        .split('/')
        .fold(node_modules_dir.to_path_buf(), |path, segment| {
            path.join(segment)
        })
        .exists()
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    #[test]
    fn discovers_local_workspace_job_node_modules() {
        let temp = TempDir::new().unwrap();
        let node_modules = temp.path().join("crates/forge-job/node_modules");
        std::fs::create_dir_all(node_modules.join("esbuild")).unwrap();
        std::fs::create_dir_all(node_modules.join("@swc/core")).unwrap();
        std::fs::create_dir_all(node_modules.join("@frontend-forge/forge-components")).unwrap();

        assert_eq!(
            find_local_node_modules_dir([temp.path().to_path_buf()], NodeModulesProfile::Job),
            Some(node_modules)
        );
    }

    #[test]
    fn discovers_local_workspace_server_node_modules_without_node_build_deps() {
        let temp = TempDir::new().unwrap();
        let node_modules = temp.path().join("crates/forge-server/node_modules");
        std::fs::create_dir_all(node_modules.join("@frontend-forge/forge-components")).unwrap();

        assert_eq!(
            find_local_node_modules_dir([temp.path().to_path_buf()], NodeModulesProfile::Server),
            Some(node_modules)
        );
    }

    #[test]
    fn skips_server_node_modules_for_job_profile() {
        let temp = TempDir::new().unwrap();
        let node_modules = temp.path().join("crates/forge-server/node_modules");
        std::fs::create_dir_all(node_modules.join("@frontend-forge/forge-components")).unwrap();

        assert_eq!(
            find_local_node_modules_dir([temp.path().to_path_buf()], NodeModulesProfile::Job),
            None
        );
    }
}
